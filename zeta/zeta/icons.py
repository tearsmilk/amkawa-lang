@lru_cache(maxsize=128)
def icon(name, ink="#141413", accent="#D97757", scale=2):
    rows = [r.ljust(16, ".")[:16] for r in ICONS[name].strip("\n").split("\n")][:16]
    img = QImage(16, 16, QImage.Format_ARGB32)
    img.fill(0)
    light = QColor(ink)
    light.setAlpha(70)
    colors = {"#": QColor(ink), "o": QColor(accent), "+": light}
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in colors:
                img.setPixelColor(x, y, colors[ch])
    pix = QPixmap.fromImage(img.scaled(16 * scale, 16 * scale, Qt.IgnoreAspectRatio, Qt.FastTransformation))
    pix.setDevicePixelRatio(scale / 1.0 if scale > 1 else 1)
    return QIcon(pix)
